-- Run this SQL in Supabase: Dashboard -> SQL Editor -> New query.
-- This lets anyone submit a wish, but prevents reading wish contents until
-- the wedding time (7 Nov 2026, 4:00 PM Egypt time / UTC+02:00).
-- The website uses only the public anon key; never use service_role in HTML.

create table if not exists public.guest_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.guest_wishes enable row level security;

drop policy if exists "Anyone can submit a guest wish" on public.guest_wishes;
create policy "Anyone can submit a guest wish"
on public.guest_wishes
for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 40
  and char_length(trim(message)) between 1 and 500
);

drop policy if exists "Wishes are readable after wedding time" on public.guest_wishes;
create policy "Wishes are readable after wedding time"
on public.guest_wishes
for select
to anon, authenticated
using (now() >= timestamptz '2026-11-07 14:00:00+00');

grant usage on schema public to anon, authenticated;
grant insert (name, message) on public.guest_wishes to anon, authenticated;
grant select (name, message, created_at) on public.guest_wishes to anon, authenticated;
